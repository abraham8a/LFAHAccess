import { readFileSync } from 'node:fs';
import { strict as assert } from 'node:assert';
import vm from 'node:vm';
const html = readFileSync(new URL('../index.html', import.meta.url), 'utf8');
const marker1 = '// VALIDATION_START';
const marker2 = '// VALIDATION_END';
assert.ok(html.includes(marker1) && html.includes(marker2));
const source = html.split(marker1)[1].split(marker2)[0].split('\n').slice(1).join('\n');
const run = (text,date) => vm.runInNewContext(`${source}\nvalidateQR(${JSON.stringify(text)}, new Date(${JSON.stringify(date)}))`, {Date, Intl});
const good = 'El que confia en Jehova es feliz  15 de noviembre del 2026';
assert.equal(run(good,'2026-11-15T18:00:00Z').valid,true,'correct QR on event day');
assert.equal(run(good,'2026-11-15T05:59:59Z').valid,false,'before midnight in Chicago');
assert.equal(run(good,'2026-11-16T05:59:59Z').valid,true,'last seconds of local day');
assert.equal(run(good,'2026-11-16T06:00:00Z').valid,false,'after midnight in Chicago');
assert.equal(run(good.replace('  15',' 15'),'2026-11-15T18:00:00Z').valid,false,'different spacing');
assert.equal(run(good.replace('Jehova','Jehová'),'2026-11-15T18:00:00Z').valid,false,'different accents');
assert.equal(run(good.replace('2026','2027'),'2026-11-15T18:00:00Z').valid,false,'different QR year');
assert.equal(run('AUTHORIZED','2026-11-15T18:00:00Z').valid,false,'old generic phrase rejected');
assert.ok(html.includes('inset:0') && html.includes('#invalidFeedback.visible') && html.includes('animation:flash-red'));
assert.ok(!html.includes('fetch('),'no Cloudflare API');
console.log('9 checks passed: strict QR, date in America/Chicago, red full-screen, no remote API.');
